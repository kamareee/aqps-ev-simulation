"""
LaTeX tables (booktabs) from the committed summaries. Each file is a complete table environment
for \\input{} in the manuscript; captions are drafts and are finalised in the manuscript stage.

Run from the repo root:  python -m postprocess.make_tables
"""

import os

import numpy as np
import pandas as pd

from . import common as C

SC = {"S1_Baseline": "S1", "S2_Contention": "S2", "S3_PeakStress": "S3"}


def f(x, d=1):
    if x is None or (isinstance(x, float) and not np.isfinite(x)):
        return "--"
    t = f"{x:,.{d}f}".replace(",", "{,}")
    return "$-$" + t[1:] if t.startswith("-") else t


def pm(mean, half, d=1):
    return f"{f(mean, d)} $\\pm$ {f(half, d)}"


def write(name, body):
    os.makedirs(C.TAB_DIR, exist_ok=True)
    with open(os.path.join(C.TAB_DIR, name + ".tex"), "w") as fh:
        fh.write("% generated by postprocess/make_tables.py -- do not edit by hand\n" + body)
    print("  table", name)


def table(env, caption, label, colspec, header, rows, size="\\footnotesize", notes=None, colsep=None):
    out = [f"\\begin{{{env}}}[!t]", "\\centering", size] + ([f"\\setlength{{\\tabcolsep}}{{{colsep}}}"] if colsep else []) + [ f"\\caption{{{caption}}}", f"\\label{{{label}}}",
           f"\\begin{{tabular}}{{{colspec}}}", "\\toprule", header + " \\\\", "\\midrule"]
    out += rows
    out += ["\\bottomrule", "\\end{tabular}"]
    if notes:
        out.append(f"\\par\\vspace{{2pt}}\\parbox{{\\linewidth}}{{\\scriptsize {notes}}}")
    out.append(f"\\end{{{env}}}\n")
    return "\n".join(out)


# ----------------------------------------------------------------------------- inputs
def tab_tou():
    t = C.cfg()["tariff"]
    rows = []
    for k, lab in [("off_peak", "Off-peak"), ("shoulder", "Shoulder"), ("peak", "Peak")]:
        win = ", ".join(f"{a:02d}:00--{b % 24:02d}:00" for a, b in t[k]["windows"])
        rows.append(f"{lab} & {win} & {t[k]['price']:.2f} \\\\")
    write("tab_tou", table("table", "Time-of-use tariff (AEST).", "tab:tou", "llr",
                           "Tier & Hours & Price (\\$/kWh)", rows))


def tab_scenarios():
    cf = C.cfg()["fleets"]
    rows = []
    for n in (45, 90):
        d = C.fleet_data(n)
        fl = cf[n] if n in cf else cf[str(n)]
        for s in C.SCEN:
            m = d["metadata"]["contention"][s]
            rows.append(f"{n} & {fl['n_evse']} & {int(fl['site_kw'])} & {SC[s]} & {f(100 * m['priority_share'], 1)} & "
                        f"{f(m['peak_present_over_evse'], 2)} & {f(m['daytime_energy_over_site_capacity'], 2)} & "
                        f"{f(m['total_session_energy_kwh'], 0)} \\\\")
        if n == 45:
            rows.append("\\addlinespace")
    write("tab_scenarios", table(
        "table*", "Scenarios. Contention is defined before any run: peak number of vehicles present per EVSE, "
                  "and daytime energy demand over site capacity in the contention window.",
        "tab:scenarios", "rrrlrrrr",
        "EVs & EVSEs & $P_\\mathrm{site}$ (kW) & Scenario & Priority share (\\%) & Peak present / EVSE & "
        "Daytime energy / capacity & Session energy (kWh)", rows))


# ----------------------------------------------------------------------------- E1
def tab_e1_master():
    d = C.runs("E1")
    rows = []
    for n in (45, 90):
        for s in C.SCEN:
            rows.append(f"\\multicolumn{{10}}{{l}}{{\\textit{{{n} EVs, {C.SCEN_LABEL[s]}}}}} \\\\")
            for m in C.TAB_METHODS:
                r = d[(d.fleet_size == n) & (d.scenario == s) & (d.method == m)].iloc[0]
                greedy = m in ("LLF", "EDF")
                rows.append(
                    f"\\quad {C.LABEL[m]} & {f(r.mission_sufficiency_pct)} & {f(r.priority_session_fulfil_pct)} & "
                    f"{f(r.nonpriority_fulfil_pct)} & {f(r.nonpriority_fulfil_22h_pct)} & {f(r.energy_total_kwh, 0)} & "
                    f"{f(r.cost_total, 0)} & {f(r.unit_cost_per_kwh, 3)} & {f(r.peak_kw, 0)} & "
                    f"{'--' if greedy else int(r.total_solves)} \\\\")
            if not (n == 90 and s == C.SCEN[-1]):
                rows.append("\\addlinespace")
    notes = ("Mission: priority vehicles reaching $E^\\mathrm{mission}$. Priority session and non-priority: delivered / "
             "requested session energy. Non-pr. 22:00: same at 22:00. Solves: all optimiser solves (Layer 0, Layer 2, "
             "preview); LLF and EDF use none. Offline-Opt. is a perfect-information MIQP bound (one solve).")
    write("tab_e1_master", table(
        "table*", "Main results on the reference AEMO day (E1).", "tab:e1", "lrrrrrrrrr",
        "Method & Mission (\\%) & Priority session (\\%) & Non-pr. (\\%) & Non-pr. 22:00 (\\%) & Energy (kWh) & "
        "Cost (\\$) & \\$/kWh & Peak (kW) & Solves", rows, notes=notes))


