def tab_e3():
    d = C.runs("E3")
    meths = [m for m in C.TAB_METHODS if m in set(d.method)]
    rows = []
    for m in meths:
        x = d[d.method == m]
        cells = [pm(*C.ci95(x[c]), dd) for c, dd in
                 [("mission_sufficiency_pct", 1), ("nonpriority_fulfil_pct", 1), ("nonpriority_fulfil_22h_pct", 1),
                  ("energy_total_kwh", 0), ("unit_cost_per_kwh", 4)]]
        rows.append(f"{C.LABEL[m]} & " + " & ".join(cells) + f" & {int((x.mission_sufficiency_pct < 100).sum())} \\\\")
    n = d.seed.nunique()
    write("tab_e3_montecarlo", table(
        "table*", f"Random disruptions, 90 EVs, S3, {n} seeds (E3): mean $\\pm$ 95\\,\\% confidence half-width.",
        "tab:e3", "lrrrrrr",
        "Method & Mission (\\%) & Non-pr. (\\%) & Non-pr. 22:00 (\\%) & Energy (kWh) & \\$/kWh & Seeds $<$100\\,\\% mission",
        rows))


# ----------------------------------------------------------------------------- E5
def tab_e5():
    d = C.runs("E5")
    a = d[d.part == "a_et_vs_every_step"]
    rows = []
    for n in (45, 90):
        for s in C.SCEN:
            rt = a[(a.fleet_size == n) & (a.scenario == s) & (a.method == "AQPS-RT")].iloc[0]
            et = a[(a.fleet_size == n) & (a.scenario == s) & (a.method == "AQPS-RT-ET")].iloc[0]
            rows.append(
                f"{n} & {SC[s]} & {int(rt.l2_solves)} / {int(et.l2_solves)} & "
                f"{f(100 * (1 - et.l2_solves / rt.l2_solves), 0)} & {int(rt.total_solves)} / {int(et.total_solves)} & "
                f"{f(100 * (1 - et.total_solves / rt.total_solves), 0)} & {f(et.l2_solve_ms_mean, 1)} / "
                f"{f(et.l2_solve_ms_p95, 1)} & {f(et.mission_sufficiency_pct - rt.mission_sufficiency_pct, 2)} & "
                f"{f(et.nonpriority_fulfil_pct - rt.nonpriority_fulfil_pct, 2)} & "
                f"{f(1000 * (et.unit_cost_per_kwh - rt.unit_cost_per_kwh), 2)} \\\\")
    write("tab_e5_et", table(
        "table*", "Event-triggered (RT-ET) versus every-step (RT) re-optimisation (E5a). $\\Delta$ = RT-ET $-$ RT.",
        "tab:e5a", "rlrrrrrrrr",
        "EVs & Scen. & L2 solves RT / ET & Red. (\\%) & Total solves RT / ET & Red. (\\%) & ET L2 ms mean / p95 & "
        "$\\Delta$ mission (pp) & $\\Delta$ non-pr. (pp) & $\\Delta$ \\$/MWh", rows))

    b = d[d.part == "b_tmax_sweep"].sort_values("t_max_steps")
    step = C.cfg()["time"]["step_minutes"]
    rows = [f"{int(r.t_max_steps * step)} & {int(r.l2_solves)} & {int(r.total_solves)} & {f(r.nonpriority_fulfil_pct, 2)} & "
            f"{f(r.unit_cost_per_kwh, 4)} \\\\" for r in b.itertuples()]
    write("tab_e5_tmax", table(
        "table", "Periodic re-solve interval $T_\\mathrm{max}$, 90 EVs, S2 (E5b).", "tab:e5b", "rrrrr",
        "$T_\\mathrm{max}$ (min) & L2 solves & Total solves & Non-pr. (\\%) & \\$/kWh", rows))

    c = d[d.part == "c_scalability"]
    rows = []
    for n in (45, 90, 180):
        for ratio in (2, 3, 4):
            g = c[(c.fleet_size == n) & (c.ratio == ratio)].set_index("method")
            et = g.loc["AQPS-RT-ET"]
            cells = []
            for m in ("LLF", "EDF", "AQPS-RT-ET"):
                r = g.loc[m]
                cells += [f(r.mission_sufficiency_pct), f(r.nonpriority_fulfil_pct), f(r.unit_cost_per_kwh, 3)]
            rows.append(f"{n} & {int(et.n_evse)} & {ratio}:1 & " + " & ".join(cells) +
                        f" & {f(et.l2_solve_ms_mean, 1)} / {f(et.l2_solve_ms_p95, 1)} \\\\")
        if n != 180:
            rows.append("\\addlinespace")
    head = ("\\multicolumn{3}{c}{} & \\multicolumn{3}{c}{LLF} & \\multicolumn{3}{c}{EDF} & "
            "\\multicolumn{4}{c}{AQPS-RT-ET} \\\\\n\\cmidrule(lr){4-6}\\cmidrule(lr){7-9}\\cmidrule(lr){10-13}\n"
            "EVs & EVSEs & EV:EVSE & Miss. & Non-pr. & \\$/kWh & Miss. & Non-pr. & \\$/kWh & Miss. & Non-pr. & \\$/kWh & "
            "L2 ms mean / p95")
    write("tab_e5_scal", table(
        "table*", "Fleet size and EV:EVSE ratio, S2 (E5c). Mission and non-priority in \\%.", "tab:e5c",
        "rrrrrrrrrrrrr", head, rows))


