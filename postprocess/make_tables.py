            rows.append(f"{n} & {ratio}:1 ({int(et.n_evse)}) & " + " & ".join(cells) +
                        f" & {f(et.l2_solve_ms_mean, 0)} / {f(et.l2_solve_ms_p95, 0)} \\\\")
