"""
LaTeX tables (booktabs) from the committed summaries. Each file is a complete table environment
for \\input{} in the manuscript; captions are drafts and are finalised in the manuscript stage.

Run from the repo root:  python -m postprocess.make_tables
"""

import os

import numpy as np
import pandas as pd

from . import common as C

SC = {"S1_Baseline": "S1", "S2_Contention": "S2", "S3_PeakStress": "S3"}


def f(x, d=1):
    if x is None or (isinstance(x, float) and not np.isfinite(x)):
        return "--"
    t = f"{x:,.{d}f}".replace(",", "{,}")
    return "$-$" + t[1:] if t.startswith("-") else t


def H(*lines):
    """Stacked (multi-line) column header."""
    return "\\begin{tabular}[b]{@{}c@{}}" + "\\\\".join(lines) + "\\end{tabular}"


def pm(mean, half, d=1):
    return f"{f(mean, d)} $\\pm$ {f(half, d)}"


def write(name, body):
    os.makedirs(C.TAB_DIR, exist_ok=True)
    with open(os.path.join(C.TAB_DIR, name + ".tex"), "w", encoding="utf-8", newline="\n") as fh:  # LF on every OS
        fh.write("% generated by postprocess/make_tables.py -- do not edit by hand\n" + body)
    print("  table", name)


def table(env, caption, label, colspec, header, rows, size="\\footnotesize", notes=None, colsep=None):
    out = [f"\\begin{{{env}}}[{'!t' if env.endswith('*') else '!htbp'}]", "\\centering", size] + ([f"\\setlength{{\\tabcolsep}}{{{colsep}}}"] if colsep else []) + [ f"\\caption{{{caption}}}", f"\\label{{{label}}}",
           f"\\begin{{tabular}}{{{colspec}}}", "\\toprule", header + " \\\\", "\\midrule"]
    out += rows
    out += ["\\bottomrule", "\\end{tabular}"]
    if notes:
        out.append(f"\\par\\vspace{{2pt}}\\parbox{{\\linewidth}}{{\\scriptsize {notes}}}")
    out.append(f"\\end{{{env}}}\n")
    return "\n".join(out)


# ----------------------------------------------------------------------------- inputs
def tab_tou():
    t = C.cfg()["tariff"]
    rows = []
    for k, lab in [("off_peak", "Off-peak"), ("shoulder", "Shoulder"), ("peak", "Peak")]:
        win = ", ".join(f"{a:02d}:00--{b % 24:02d}:00" for a, b in t[k]["windows"])
        rows.append(f"{lab} & {win} & {t[k]['price']:.2f} \\\\")
    write("tab_tou", table("table", "Time-of-use tariff (AEST).", "tab:tou", "llr",
                           "Tier & Hours & Price (\\$/kWh)", rows))


def tab_scenarios():
    cf = C.cfg()["fleets"]
    rows = []
    for n in (45, 90):
        d = C.fleet_data(n)
        fl = cf[n] if n in cf else cf[str(n)]
        for s in C.SCEN:
            m = d["metadata"]["contention"][s]
            rows.append(f"{n} & {fl['n_evse']} & {int(fl['site_kw'])} & {SC[s]} & {f(100 * m['priority_share'], 1)} & "
                        f"{f(m['peak_present_over_evse'], 2)} & {f(m['daytime_energy_over_site_capacity'], 2)} & "
                        f"{f(m['total_session_energy_kwh'], 0)} \\\\")
        if n == 45:
            rows.append("\\addlinespace")
    write("tab_scenarios", table(
        "table*", "Scenarios. Contention is defined before any run: peak number of vehicles present per EVSE, "
                  "and daytime energy demand over site capacity in the contention window.",
        "tab:scenarios", "rrrlrrrr",
        f"EVs & EVSEs & {H('$P_\\mathrm{site}$', '(kW)')} & Scenario & {H('Priority', 'share (\\%)')} & "
        f"{H('Peak present', 'per EVSE')} & {H('Daytime energy', '/ capacity')} & {H('Session', 'energy (kWh)')}",
        rows))


